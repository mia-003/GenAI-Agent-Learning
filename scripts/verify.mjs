import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url),M=require('../workbench/model.js');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'agent-workbench-verify-'));
try {
  for(const dir of ['workbench','scripts','01-学习计划/周任务']) fs.cpSync(path.join(root,dir),path.join(tmp,dir),{recursive:true});
  const dir=path.join(tmp,'04-章节笔记');fs.mkdirSync(dir,{recursive:true});
  const privateText='---\npublish: false\n---\n# Private\nPRIVATE_CANARY\n';
  const publicText='---\npublish: true\n---\n# 公开笔记\n';
  fs.writeFileSync(path.join(dir,'private.md'),privateText);fs.writeFileSync(path.join(dir,'public.md'),publicText);
  const weekPath=path.join(tmp,'01-学习计划/周任务/周任务安排W1.md');let weekText=fs.readFileSync(weekPath,'utf8');weekText=weekText.replace(/- \[ \] W1D1/, '- [x] W1D1');fs.writeFileSync(weekPath,weekText);
  const build=()=>execFileSync(process.execPath,[path.join(tmp,'scripts/build.mjs')]);build();
  let data=JSON.parse(fs.readFileSync(path.join(tmp,'docs/data.json')));
  assert.equal(M.stats(data,'2026-11-03').days,1);
  assert.equal(M.stats(data).hours,0);
  assert.equal(data.logs[0].date!==undefined,true);
  assert(!JSON.stringify(data).includes('PRIVATE_CANARY'));
  assert(!fs.existsSync(path.join(tmp,'04-学习记录')));
  assert.equal(fs.readdirSync(path.join(tmp,'public-notes')).filter(n=>n.endsWith('.md')).length,1);
  fs.writeFileSync(path.join(dir,'public.md'),publicText.replace('publish: true','publish: false'));fs.writeFileSync(weekPath,fs.readFileSync(weekPath,'utf8').replace(/- \[ \] W1D2/, '- [x] W1D2'));build();
  data=JSON.parse(fs.readFileSync(path.join(tmp,'docs/data.json')));
  assert.equal(M.stats(data).days,2);
  assert.equal(fs.readdirSync(path.join(tmp,'public-notes')).filter(n=>n.endsWith('.md')).length,0);
  console.log('PASS: weekly-plan daily completion, unknown time, private text filtering, publish removal, no daily files.');
} finally {fs.rmSync(tmp,{recursive:true,force:true});}
